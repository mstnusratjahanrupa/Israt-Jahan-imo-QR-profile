// Helper to remove any duplicates while preserving top priority ordering
export const countriesList: Country[] = (() => {
  const seen = new Set<string>();
  const list: Country[] = [];
  for (const c of allCountries) {
    const key = `${c.name}_${c.code}`;
    if (!seen.has(key)) {
      seen.add(key);
      list.push(c);
    }
  }
  return list;
})();
